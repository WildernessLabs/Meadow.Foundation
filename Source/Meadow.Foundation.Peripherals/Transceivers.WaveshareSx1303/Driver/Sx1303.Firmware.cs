    // Max chunk size for SPI memory transfers (FTDI USB buffer limited)
    private const int MEM_CHUNK_SIZE = 1024;

    /// <summary>
    /// Writes a block of data to the SX1302 internal memory via SPI burst write.
    /// Chunks the transfer to stay within FTDI USB buffer limits.
    /// </summary>
    private void MemoryWrite(ushort startAddr, byte[] data)
    {
        int offset = 0;
        while (offset < data.Length)
        {
            int chunkLen = Math.Min(MEM_CHUNK_SIZE, data.Length - offset);
            ushort addr = (ushort)(startAddr + offset);

            byte[] tx = new byte[3 + chunkLen];
            tx[0] = SPI_MUX_SX1302;
            tx[1] = (byte)(((addr >> 8) & 0x7F) | 0x80);
            tx[2] = (byte)(addr & 0xFF);
            Array.Copy(data, offset, tx, 3, chunkLen);
            _spi.Write(_cs, tx);

            offset += chunkLen;
        }
    }

    /// <summary>
    /// Reads a block of data from the SX1302 internal memory via SPI burst read.
    /// Chunks the transfer to stay within FTDI USB buffer limits.
    /// </summary>
    private byte[] MemoryRead(ushort startAddr, int length)
    {
        byte[] result = new byte[length];
        int offset = 0;
        while (offset < length)
        {
            int chunkLen = Math.Min(MEM_CHUNK_SIZE, length - offset);
            ushort addr = (ushort)(startAddr + offset);

            byte[] tx = new byte[4 + chunkLen];
            byte[] rx = new byte[4 + chunkLen];
            tx[0] = SPI_MUX_SX1302;
            tx[1] = (byte)((addr >> 8) & 0x7F);
            tx[2] = (byte)(addr & 0xFF);
            _spi.Exchange(_cs, tx, rx);

            Array.Copy(rx, 4, result, offset, chunkLen);
            offset += chunkLen;
        }
        return result;
    }

    /// <summary>
    /// Loads firmware into an MCU, verifies it, and releases the MCU from reset.
    /// </summary>
    private void LoadMcuFirmware(Registers ctrlReg, ushort memAddr, byte[] firmware)
    {
        if (firmware.Length != MCU_FW_SIZE)
            throw new ArgumentException($"Firmware must be exactly {MCU_FW_SIZE} bytes, got {firmware.Length}");

        // AgcMcuCtrl / ArbMcuCtrl bit layout:
        //   bit 0 = PARITY_ERROR (read-only)
        //   bit 1 = HOST_PROG
        //   bit 2 = MCU_CLEAR
        //   bit 3 = FORCE_HOST_FE_CTRL
        //   bit 4 = CLK_EN
        WriteBitField(ctrlReg, 2, 1, 1);  // MCU_CLEAR = 1
        WriteBitField(ctrlReg, 1, 1, 1);  // HOST_PROG = 1
        WriteRegister(Registers.CommonPage, 0x00);

        MemoryWrite(memAddr, firmware);

        byte[] readBack = MemoryRead(memAddr, MCU_FW_SIZE);
        for (int i = 0; i < MCU_FW_SIZE; i++)
        {
            if (readBack[i] != firmware[i])
                throw new Exception($"Firmware verify failed at offset 0x{i:X4}: " +
                                    $"wrote 0x{firmware[i]:X2}, read 0x{readBack[i]:X2}");
        }

        WriteBitField(ctrlReg, 1, 1, 0);  // HOST_PROG = 0
        WriteBitField(ctrlReg, 2, 1, 0);  // MCU_CLEAR = 0 (starts running)

        Task.Delay(10).Wait(); // give MCU time to start

        byte ctrl = ReadRegister(ctrlReg);
        if ((ctrl & 0x01) != 0)  // bit 0 = PARITY_ERROR
            throw new Exception($"MCU firmware parity error after load (ctrl=0x{ctrl:X2})");
    }

    /// <summary>
    /// Loads and starts the AGC MCU firmware, then performs the mailbox handshake.
    /// </summary>
    public void LoadAgcFirmware()
    {
        LoadMcuFirmware(Registers.AgcMcuCtrl, AGC_MEM_ADDR, AgcFirmwareSx1250);
        AgcHandshake();
    }

    /// <summary>
    /// Loads and starts the ARB MCU firmware, then performs the debug register handshake.
    /// </summary>
    public void LoadArbFirmware()
    {
        LoadMcuFirmware(Registers.ArbMcuCtrl, ARB_MEM_ADDR, ArbFirmware);
        ArbHandshake();
    }

    // ---- AGC Mailbox Protocol ----

    private void AgcMailboxWrite(int mailboxId, byte value)
    {
        WriteRegister((ushort)(0x578C - mailboxId), value);
    }

    private byte AgcMailboxRead(int mailboxId)
    {
        return ReadRegister((ushort)(0x5790 - mailboxId));
    }

    private void AgcWaitStatus(byte expected, int timeoutMs = 1000)
    {
        for (int i = 0; i < timeoutMs; i++)
        {
            byte status = ReadRegister(Registers.AgcMcuMcuAgcStatus);
            if (status == expected) return;
            Task.Delay(1).Wait();
        }
        throw new TimeoutException($"AGC MCU: expected status 0x{expected:X2}, timed out");
    }

    private void AgcNotifyAndWait(byte notifyValue, byte expectedStatus)
    {
        AgcMailboxWrite(3, notifyValue);
        AgcWaitStatus(expectedStatus);
    }

    private void AgcHandshake()
    {
        AgcWaitStatus(0x01);
        byte fwVersion = AgcMailboxRead(0);
        if (fwVersion != FW_VERSION_AGC_SX1250)
            throw new Exception($"AGC firmware version mismatch: expected {FW_VERSION_AGC_SX1250}, got {fwVersion}");

        // Radio A gains (auto)
        AgcMailboxWrite(0, 0xFF); AgcMailboxWrite(1, 0xFF); AgcMailboxWrite(2, 0x00);
        AgcNotifyAndWait(0x80, 0x02);

        // Radio B gains (auto)
        AgcMailboxWrite(0, 0xFF); AgcMailboxWrite(1, 0xFF); AgcMailboxWrite(2, 0x00);
        AgcNotifyAndWait(0x20, 0x03);

        // Ana gain min/max
        AgcMailboxWrite(0, 1); AgcMailboxWrite(1, 13);
        AgcNotifyAndWait(0x03, 0x04);

        // Ana thresholds
        AgcMailboxWrite(0, 3); AgcMailboxWrite(1, 12);
        AgcNotifyAndWait(0x04, 0x05);

        // Dec attenuation min/max
        AgcMailboxWrite(0, 4); AgcMailboxWrite(1, 15);
        AgcNotifyAndWait(0x05, 0x06);

        // Dec thresholds
        AgcMailboxWrite(0, 40); AgcMailboxWrite(1, 80); AgcMailboxWrite(2, 90);
        AgcNotifyAndWait(0x06, 0x07);

        // Channel attenuation min/max
        AgcMailboxWrite(0, 4); AgcMailboxWrite(1, 14);
        AgcNotifyAndWait(0x07, 0x08);

        // Channel thresholds
        AgcMailboxWrite(0, 52); AgcMailboxWrite(1, 132);
        AgcNotifyAndWait(0x08, 0x09);

        // SX1250 PA config
        AgcMailboxWrite(0, 0); AgcMailboxWrite(1, 7); AgcMailboxWrite(2, 4);
        AgcNotifyAndWait(0x09, 0x0A);

        // PA start delay
        AgcMailboxWrite(0, 8);
        AgcNotifyAndWait(0x0A, 0x0B);

        // LBT disabled
        AgcMailboxWrite(0, 0);
        AgcNotifyAndWait(0x0B, 0x0F);

        // Config done
        AgcMailboxWrite(3, 0x0F);
    }

    // ---- ARB Debug Register Protocol ----

    private void ArbHandshake()
    {
        for (int i = 0; i < 1000; i++)
        {
            if (ReadRegister(Registers.ArbMcuMcuArbStatus) == 0x01) break;
            if (i == 999) throw new TimeoutException("ARB MCU did not start");
            Task.Delay(1).Wait();
        }

        byte fwVersion = ReadRegister(Registers.ArbMcuArbDebugSts0);
        if (fwVersion != FW_VERSION_ARB)
            throw new Exception($"ARB firmware version mismatch: expected {FW_VERSION_ARB}, got {fwVersion}");

        WriteRegister(Registers.ArbMcuArbDebugCfg0, 7);     // debug SF = SF7
        WriteRegister(Registers.ArbMcuArbDebugCfg3, 0x00);  // no fine timestamp
        WriteRegister(Registers.ArbMcuArbDebugCfg2, 3);     // double-detect threshold
        WriteRegister(Registers.ArbMcuArbDebugCfg1, 1);     // resume

        for (int i = 0; i < 1000; i++)
        {
            if (ReadRegister(Registers.ArbMcuMcuArbStatus) == 0x00) return;
            Task.Delay(1).Wait();
        }
        throw new TimeoutException("ARB MCU did not acknowledge configuration");
    }
